'use strict';
const assert=require('node:assert/strict');
const {stripReasoningText,extractReplyEnvelope,visibleReplyText}=require('../src/visible-reply');
const {parseModelEnvelope,normalizeResponse}=require('../src/server');
const {textBlocks}=require('../src/dsh-runtime');
const first={text:'旧草稿。',messages:[{text:'旧草稿。'}],emotion:'neutral'};
const final={text:'回来啦。\n今天过得怎么样？',messages:[{text:'回来啦。'},{text:'今天过得怎么样？'}],emotion:'happy',memory_updates:[],internal_note:'never display'};
const raw=JSON.stringify(first)+'\n'+JSON.stringify(final);
assert.deepEqual(parseModelEnvelope(raw),final);
assert.equal(normalizeResponse(parseModelEnvelope(raw),'',400).text,final.text);
assert.deepEqual(parseModelEnvelope('前言\n```json\n'+raw+'\n```\n完成'),final);
assert.equal(visibleReplyText(raw),final.text);
assert.equal(visibleReplyText('{"text":"截断的内部结构'), '');
assert.throws(()=>parseModelEnvelope('{"text":"截断'),/model_reply_invalid/);
assert.throws(()=>parseModelEnvelope('{"analysis":"private scratchpad"}'),/model_reply_invalid/);
assert.throws(()=>parseModelEnvelope('<think>unfinished reasoning'),/model_reply_invalid/);
assert.equal(stripReasoningText('<think>private</think>最终台词。'),'最终台词。');
assert.equal(stripReasoningText('private prefix</think>最终台词。'),'最终台词。');
assert.equal(stripReasoningText('台词。<think>unfinished'),'台词。');
assert.equal(stripReasoningText('<analysis>one<think>two</think>three</analysis>最终台词。'),'最终台词。');
assert.equal(textBlocks([{type:'thinking',thinking:'private'},{type:'reasoning',text:'private'},{type:'text',text:'<think>private</think>'+JSON.stringify(final)}]),JSON.stringify(final));
assert.equal(normalizeResponse({messages:[{text:'<think>private</think>最终台词。'},{text:'{"analysis":"private"}'}]},'',400).text,'最终台词。');
const braces={text:'括号 {保留} 与转义引号 " 都是正文。',messages:[]};
assert.deepEqual(extractReplyEnvelope(JSON.stringify(braces)),braces);
assert.deepEqual(parseModelEnvelope('普通纯文本回复。'),{text:'普通纯文本回复。'});
assert.equal(visibleReplyText('讨论一下 JSON 的 { 和 }。'),'讨论一下 JSON 的 { 和 }。');
console.log('visible-reply: duplicate envelopes, final speech only, malformed JSON rejection, nested/unfinished reasoning, block types and quoted braces passed');
