'use strict';
const assert=require('node:assert/strict');
const {speechPlan,validSpeech,speechForMessage}=require('../src/speech-prosody');
const {normalizeResponse}=require('../src/server');
assert.deepEqual(speechPlan('晚安，安心睡吧。',{emotion:'happy'}),{style:'soft',ending:'falling'});
assert.deepEqual(speechPlan('好耶，出发！'),{style:'bright',ending:'falling'});
assert.deepEqual(speechPlan('你想先聊什么？'),{style:'neutral',ending:'rising'});
const cue={style:'serious',ending:'falling'};
assert.deepEqual(speechPlan('这难道还不够吗？',{speech:cue}),cue,'semantic rhetorical falling cue overrides punctuation');
assert.equal(validSpeech({style:'read arbitrary file',ending:'rising'}),null);
const reply=normalizeResponse({text:'晚安。',speech:{style:'soft',ending:'falling'},messages:[{text:'晚安。',speech:{style:'soft',ending:'falling'}}]},'',100);
assert.deepEqual(reply.speech,{style:'soft',ending:'falling'});assert.deepEqual(reply.messages[0].speech,reply.speech);
const mixed=normalizeResponse({speech:{style:'soft',ending:'falling'},messages:[{text:'晚安。',speech:{style:'soft',ending:'falling'}},{text:'明天十点开会。'}]},'',100);
assert.equal(mixed.messages[1].speech,undefined,'a missing sentence tag must not inherit the whole-turn soft mood');
const split=normalizeResponse({messages:[{text:'晚安。明天十点开会。',speech:{style:'soft',ending:'falling'}}]},'',100,false,'zh-CN','qq_group');
assert.ok(split.messages.length>1);assert.ok(split.messages.every(p=>!p.speech),'local sentence splitting cannot copy one soft tag to several unclassified sentences');
let queried;
const store={db:{prepare:sql=>({get:(...args)=>{queried=args;return sql.includes('reply_parts')?{body:JSON.stringify({speech:cue})}:null;}})}};
assert.deepEqual(speechForMessage(store,{session:'desktop-pet',request_id:'req:part:1',id:'qq:req:part:1',text:'你说呢？'}),cue);
assert.equal(queried[0],'desktop-pet:req:part:1:assistant');
assert.equal(normalizeResponse({text:'你好。',speech:{style:'bad',ending:'bad'}},'',100).speech,undefined);
console.log('speech-prosody: semantic cue validation, gentle context, rhetorical ending, normalization and per-part lookup passed');
