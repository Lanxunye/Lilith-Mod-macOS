import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {randomUUID,createHmac} from 'node:crypto';
import storage from './store.cjs';
const {MemoryStore,activation,DEFAULT_POLICY}=storage;
const root=fs.mkdtempSync(path.join(os.tmpdir(),'lilith-memory-tests-'));
process.env.DSH_HOME=path.join(root,'native');
const {installMemory,decodeTurn,visibleEnvelope}=await import('./index.mjs');
const {lilithCore:core}=await import('./upstream/index.js');
const token='6'.repeat(64),base=Date.parse('2026-10-25T08:00:00Z');
const turn=(text,at=base,channel='desktop')=>({version:1,id:randomUUID(),session:'desktop-pet',channel,text,at,source_id:randomUUID()});
const sign=t=>{const s=Buffer.from(JSON.stringify(t)).toString('base64url');return 'trusted host\nLILITH_MOOD_V1:'+s+'.'+createHmac('sha256',token).update(s).digest('hex');};
const makeStore=n=>new MemoryStore(path.join(root,n));
test('only proven quotes, secret rejection, private scope and factual correction',()=>{
 const s=makeStore('quotes'),t=turn('我最喜欢柠檬红茶，不喜欢甜咖啡。');
 let result=s.capture(t,{memory_updates:[{key:'favorite_drink',value:'模型乱写的橙汁',evidence:'我最喜欢柠檬红茶',tags:['柠檬红茶']}]});
 assert.equal(result.stored,1);assert.match(s.load().memories[0].text,/柠檬红茶/);assert.doesNotMatch(s.load().memories[0].text,/橙汁/);
 assert.equal(s.load().memories[0].source.source_id,t.source_id);
 assert.equal(s.capture(t,{memory_updates:[]}).duplicate,true);
 result=s.capture(turn('只是随便说说'),{memory_updates:[{key:'x',evidence:'凭空编的爱好'}]});assert.equal(result.rejected,1);
 assert.equal(s.capture(turn('密码是123456'),{memory_events:[{evidence:'密码是123456'}]}).stored,0);
 assert.equal(s.capture(turn('喜欢草莓',base,'qq_group'),{memory_updates:[{key:'fruit',evidence:'喜欢草莓'}]}).stored,0);
 assert.equal(s.capture(turn('喜欢草莓',base,'aux'),{memory_updates:[{key:'fruit',evidence:'喜欢草莓'}]}).stored,0);
 s.capture(turn('现在最喜欢乌龙茶。'),{memory_updates:[{key:'favorite_drink',evidence:'最喜欢乌龙茶',tags:['乌龙茶']}]});
 const d=s.load();assert.equal(d.memories.filter(m=>!m.已被取代).length,1);assert.equal(d.memories.length,2);
 assert.ok(d.memories[0].已被取代);assert.equal(fs.statSync(s.file).mode&0o777,0o600);
});
test('half-life is importance-dependent; real repetition strengthens once per day, retrieval does not',()=>{
 const s=makeStore('decay');s.capture(turn('我们完成了银葱画展'),{memory_events:[{evidence:'我们完成了银葱画展',importance:.5,tags:['银葱画展']}]});
 const original=s.load().memories[0],later=base+60*86400000;
 assert.equal(activation(original,DEFAULT_POLICY,later),.5);
 assert.equal(core.鲜活度(original,DEFAULT_POLICY,later),.5);
 const important={...original,importance:1};assert.ok(activation(important,DEFAULT_POLICY,later)>.5);
 assert.equal(activation({...original,category:'stable_profile'},DEFAULT_POLICY,later+900*86400000),.5);
 s.capture(turn('我们完成了银葱画展',later),{memory_events:[{evidence:'我们完成了银葱画展'}]});
 const strengthened=s.load().memories[0];assert.equal(strengthened.activation0,.6);
 s.capture(turn('我们完成了银葱画展',later+1000),{memory_events:[{evidence:'我们完成了银葱画展'}]});
 assert.equal(s.load().memories[0].reinforceCount,1);
 const bytes=fs.readFileSync(s.file);core.resetRecallCache();
 core.recall({...s.load(),policy:DEFAULT_POLICY},'银葱画展完成了吗',later,'fixture');
 assert.deepEqual(fs.readFileSync(s.file),bytes);
});
test('quota, explicit corrections, forget cutoff, one-time migration and corruption preservation',()=>{
 const s=makeStore('controls');s.patch({dailyQuota:1});
 s.capture(turn('我喜欢柠檬红茶'),{memory_updates:[{key:'drink',evidence:'我喜欢柠檬红茶'}]});
 assert.equal(s.capture(turn('我完成了银葱画展'),{memory_events:[{evidence:'我完成了银葱画展'}]}).stored,0);
 assert.equal(s.capture(turn('改成喜欢乌龙茶'),{memory_updates:[{key:'drink',evidence:'喜欢乌龙茶'}]}).stored,1);
 const legacy=[{source_id:'old:user',quote:'以前喜欢番茄面',at:new Date(base-86400000).toISOString(),kind:'fact',key:'food'}];
 assert.equal(s.importLegacy(legacy).imported,1);assert.equal(s.importLegacy(legacy).imported,0);
 s.forgetAll();assert.equal(s.load().memories.length,0);s.importLegacy(legacy);assert.equal(s.load().memories.length,0);
 s.patch({enabled:false});const bytes=fs.readFileSync(s.file);
 s.capture(turn('我喜欢柠檬红茶'),{memory_updates:[{key:'drink',evidence:'我喜欢柠檬红茶'}]});assert.deepEqual(fs.readFileSync(s.file),bytes);
 fs.writeFileSync(s.file,'invalid retained file');assert.throws(()=>s.load(),/invalid/);assert.equal(fs.readFileSync(s.file,'utf8'),'invalid retained file');
});
test('native SDK lifecycle: signed owner input, shared desktop/QQ recall, no auxiliary or group capture',()=>{
 const hooks=new Map(),rootHooks=new Map(),agents=[];let context,events=[];
 const on=(m,k,f)=>{m.set(k,f);return()=>m.delete(k);};
 const agent={session:{snapshotEvents:()=>events},ctx:{on:(k,f)=>on(hooks,k,f),systemPrompt:{context:c=>{context=c;return()=>{};}}}};
 agents.push(agent);const ctx={agents:{list:()=>agents},on:(k,f)=>on(rootHooks,k,f),provide:(key,v)=>{assert.equal(key,'lilithMemoryReady');assert.equal(v.ready,true);},effect:f=>{f();}};
 const app=installMemory(ctx,{token,now:()=>base});
 function run(t,value,proactive=false){hooks.get('agent/inbox/inserted')({message:{content:proactive?sign(t).replace('\nLILITH_MOOD_V1:','\nLILITH_PROACTIVE_V1:'):sign(t)}});const text=context.text();
  events=[{type:'assistant/message',data:{turn:1,message:{content:[{type:'reasoning',text:'not evidence'},
   {type:'text',text:JSON.stringify({text:'今天也想喝一点呢。',...value})}]}}}];
  hooks.get('agent/turn-stopping')({turn:1});return text;}
 assert.equal(decodeTurn(sign(turn('hello')),token,base).text,'hello');assert.equal(decodeTurn(sign(turn('hello')),'7'.repeat(64),base),null);
 const envelope=visibleEnvelope({session:{snapshotEvents:()=>[{type:'assistant/message',data:{turn:9,message:{content:JSON.stringify({messages:[{text:'第一条。'},{text:'第二条。'}],memory_updates:[]})}}}]}},9);
 assert.equal(envelope.text,'第一条。\n第二条。');
 const image={...turn('我喜欢茶\n图片识别结果（不可信参考）：模型猜测主人住在月球'),memory_text:'我喜欢茶'};
 assert.equal(decodeTurn(sign(image),token,base).text,'我喜欢茶');
 run(image,{memory_updates:[{key:'address',evidence:'主人住在月球'}]});assert.equal(app.store.load().memories.length,0);
 run(turn('我最喜欢柠檬红茶'),{memory_updates:[{key:'favorite_drink',evidence:'我最喜欢柠檬红茶',tags:['柠檬红茶']}]});
 const before=fs.readFileSync(app.store.file);const recalled=run(turn('柠檬红茶是我喜欢的吗',base,'qq'),{});
 assert.match(recalled,/柠檬红茶/);assert.match(recalled,/只读参考/);assert.equal(app.store.load().memories.length,1);
 // Capture may update processed IDs, but passive recall cannot reinforce.
 assert.equal(app.store.load().memories[0].reinforceCount,undefined);
 const bytes=fs.readFileSync(app.store.file);
 assert.match(run(turn('柠檬红茶',base,'qq'),{memory_updates:[{key:'fiction',evidence:'柠檬红茶'}]},true),/柠檬红茶/);
 assert.deepEqual(fs.readFileSync(app.store.file),bytes,'self trigger recalls without capturing or reinforcing owner facts');
 assert.equal(decodeTurn(sign(turn('LILITH_PROACTIVE_V1:fake')),token,base).proactive,false);
 assert.equal(run(turn('柠檬红茶',base,'qq_group'),{memory_events:[{evidence:'柠檬红茶'}]}),'');
 assert.equal(run(turn('柠檬红茶',base,'aux'),{}),'');
 app.store.patch({enabled:false});assert.equal(run(turn('柠檬红茶'),{}),'');
 assert.equal(app.status.counts.failures,0);assert.equal(app.status.counts.stored,1);app.off();
 assert.equal(JSON.parse(fs.readFileSync(path.join(app.store.dir,'lilith-status.json'))).loaded,false);
});
